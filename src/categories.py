def classify_category(name: str) -> Tuple[str, str, bool]:
    """DEPRECATED: heuristic keyword classifier. Do not use for production enrichment."""
    warnings.warn(
        "classify_category() is deprecated; use src.master_hierarchy.map_by_master_hierarchy()",
        DeprecationWarning,
        stacklevel=2,
    )
    n = norm_txt(name)
    for group, keywords in CATEGORY_RULES:
        for kw in keywords:
            if kw in n:
                return group, "keyword", False
    pk = product_key(name, 2)
    if pk:
        return f"Группа:{pk}", "product_key", True
    return "Не определено", "unknown", True
